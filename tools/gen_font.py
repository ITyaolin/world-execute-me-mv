#!/usr/bin/env python3
"""Bake a plain 8x16 monospace bitmap font into a C header.

The MV program uses this bitmap font to render big "banner" keywords (it samples
the glyph as a grid of terminal cells), and the preview rasteriser
(tools/mvframe2png.py) parses the very same header to draw frames as PNG, so the
baked font is the single source of truth for both.

Glyphs are rasterised from a real monospace TTF with ImageMagick, one glyph per
fixed 8x16 canvas, always at the same baseline so the set stays visually
consistent.

Usage:
  tools/gen_font.py                     # -> src/font_data.h
  tools/gen_font.py --print             # also dump ASCII proof sheet to stdout
  tools/gen_font.py --font /path.ttf --pointsize 13 --baseline 13
"""
import argparse
import os
import subprocess
import sys

FIRST, LAST = 32, 126
CELL_W, CELL_H = 8, 16
DEFAULT_FONT = "/usr/share/fonts/liberation/LiberationMono-Regular.ttf"


def have(cmd):
    return subprocess.call(["sh", "-c", "command -v %s >/dev/null 2>&1" % cmd]) == 0


def im_cmd():
    if have("magick"):
        return ["magick"]
    if have("convert"):
        return ["convert"]
    sys.exit("error: need ImageMagick (magick or convert) on PATH")


def render_glyph(im, font, pointsize, baseline, ch):
    """Return CELL_H row bitmasks (bit 7 = leftmost pixel) for one character."""
    img = "%dx%d" % (CELL_W, CELL_H)
    cmd = im + [
        "-size", img, "xc:black",
        "-font", font,
        "-pointsize", str(pointsize),
        "-fill", "white",
        "-annotate", "+0+%d" % baseline, ch,
        "-depth", "8", "txt:-",
    ]
    out = subprocess.run(cmd, capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("error: ImageMagick failed for %r:\n%s" % (ch, out.stderr))
    rows = [0] * CELL_H
    seen = 0
    for line in out.stdout.splitlines():
        if not line or line[0] == "#":
            continue
        # "x,y: (g)  #HEX  gray(NN)"
        head, _, rest = line.partition(":")
        try:
            x, y = (int(v) for v in head.split(","))
        except ValueError:
            continue
        if not (0 <= x < CELL_W and 0 <= y < CELL_H):
            continue
        seen += 1
        val = None
        if "(" in rest:
            val = rest.split("(", 1)[1].split(")", 1)[0].split(",")[0]
        if val is None:
            continue
        try:
            g = float(val)
        except ValueError:
            continue
        if g * 255.0 >= 128.0:
            rows[y] |= 1 << (CELL_W - 1 - x)
    if seen != CELL_W * CELL_H:
        sys.exit("error: bad pixel dump for %r (%d pixels)" % (ch, seen))
    return rows


def proof_sheet(glyphs, per_row=16):
    """Yield human-readable ASCII art of glyphs for eyeballing."""
    lines = []
    for base in range(FIRST, LAST + 1, per_row):
        chunk = [c for c in range(base, min(base + per_row, LAST + 1))]
        lines.append("  ".join(" %3d %-3s" % (c, repr(chr(c))[1:-1]) for c in chunk))
        for r in range(CELL_H):
            cells = []
            for c in chunk:
                bits = glyphs[c - FIRST][r]
                cells.append("".join("#" if bits & (1 << (CELL_W - 1 - i)) else "."
                                     for i in range(CELL_W)))
            lines.append("  ".join(cells))
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--pointsize", type=int, default=13)
    ap.add_argument("--baseline", type=int, default=13)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "font_data.h"))
    ap.add_argument("--print", dest="do_print", action="store_true")
    args = ap.parse_args()

    if not os.path.exists(args.font):
        sys.exit("error: font not found: %s" % args.font)
    im = im_cmd()
    glyphs = [render_glyph(im, args.font, args.pointsize, args.baseline, chr(c))
              for c in range(FIRST, LAST + 1)]

    if args.do_print:
        print(proof_sheet(glyphs))

    out = os.path.abspath(args.out)
    with open(out, "w") as fh:
        fh.write("/* Generated by tools/gen_font.py -- do not edit by hand.\n"
                 " * 8x16 bitmap font for ASCII %d..%d, baked from:\n"
                 " *   %s (pointsize %d, baseline %d)\n"
                 " * Row byte: bit 7 = leftmost pixel. */\n"
                 % (FIRST, LAST, os.path.basename(args.font), args.pointsize, args.baseline))
        fh.write("#ifndef MV_FONT_DATA_H\n#define MV_FONT_DATA_H\n\n")
        fh.write("#define FONT_FIRST %d\n#define FONT_LAST %d\n" % (FIRST, LAST))
        fh.write("#define FONT_W %d\n#define FONT_H %d\n" % (CELL_W, CELL_H))
        fh.write("#define FONT_GLYPHS %d\n\n" % (LAST - FIRST + 1))
        fh.write("static const unsigned char FONT_BITS[FONT_GLYPHS][FONT_H] = {\n")
        for i, c in enumerate(range(FIRST, LAST + 1)):
            body = ",".join("0x%02x" % b for b in glyphs[i])
            tag = chr(c) if chr(c) not in "\\\"" else "\\" + chr(c)
            fh.write("    { %s }, /* %3d  %s */\n" % (body, c, tag))
        fh.write("};\n\n#endif /* MV_FONT_DATA_H */\n")
    print("wrote %s (%d glyphs, %dx%d)" % (out, LAST - FIRST + 1, CELL_W, CELL_H))


if __name__ == "__main__":
    main()